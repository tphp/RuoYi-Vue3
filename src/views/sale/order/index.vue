<template>
  <div class="app-container">
    <!-- 搜索栏 -->
    <el-form :model="queryParams" ref="queryRef" :inline="true" v-show="showSearch">
      <el-form-item :label="$t('sale.orderNo')" prop="orderNo">
        <el-input v-model="queryParams.orderNo" :placeholder="$t('sale.orderNoPlaceholder')" clearable style="width: 200px" @keyup.enter="handleQuery" />
      </el-form-item>
      <el-form-item :label="$t('sale.customerName')" prop="customerName">
        <el-input v-model="queryParams.customerName" :placeholder="$t('sale.customerNamePlaceholder')" clearable style="width: 200px" @keyup.enter="handleQuery" />
      </el-form-item>
      <el-form-item :label="$t('sale.orderStatus')" prop="orderStatus">
        <el-select v-model="queryParams.orderStatus" :placeholder="$t('sale.orderStatusPlaceholder')" clearable style="width: 200px">
          <el-option v-for="dict in sale_order_status" :key="dict.value" :label="dict.label" :value="dict.value" />
        </el-select>
      </el-form-item>
      <el-form-item :label="$t('sale.orderDate')">
        <el-date-picker v-model="dateRange" value-format="YYYY-MM-DD" type="daterange" range-separator="-" start-:placeholder="$t('common.startDate')" end-:placeholder="$t('common.endDate')" />
      </el-form-item>
      <el-form-item>
        <el-button type="primary" icon="Search" @click="handleQuery">{{ $t('common.search') }}</el-button>
        <el-button icon="Refresh" @click="resetQuery">{{ $t('common.reset') }}</el-button>
      </el-form-item>
    </el-form>

    <!-- 操作按钮 -->
    <el-row :gutter="10" class="mb8">
      <el-col :span="1.5">
        <el-button type="primary" plain icon="Plus" @click="handleAdd" v-hasPermi="['sale:order:add']">{{ $t('common.add') }}</el-button>
      </el-col>
      <el-col :span="1.5">
        <el-button type="success" plain icon="Edit" :disabled="single" @click="handleUpdate" v-hasPermi="['sale:order:edit']">{{ $t('common.edit') }}</el-button>
      </el-col>
      <el-col :span="1.5">
        <el-button type="danger" plain icon="Delete" :disabled="multiple" @click="handleDelete" v-hasPermi="['sale:order:remove']">{{ $t('common.delete') }}</el-button>
      </el-col>
      <el-col :span="1.5">
        <el-button type="warning" plain icon="Download" @click="handleExport" v-hasPermi="['sale:order:export']">{{ $t('common.export') }}</el-button>
      </el-col>
      <right-toolbar v-model:showSearch="showSearch" @queryTable="getList"></right-toolbar>
    </el-row>

    <!-- 列表表格 -->
    <el-table v-loading="loading" :data="orderList" @selection-change="handleSelectionChange">
      <el-table-column type="selection" width="55" align="center" />
      <el-table-column :label="$t('sale.orderNo')" align="center" prop="orderNo" width="160" />
      <el-table-column :label="$t('sale.customerName')" align="center" prop="customerName" :show-overflow-tooltip="true" />
      <el-table-column :label="$t('sale.orderDate')" align="center" prop="orderDate" width="120" />
      <el-table-column :label="$t('sale.orderStatus')" align="center" prop="orderStatus" width="100">
        <template #default="scope">
          <dict-tag :options="sale_order_status" :value="scope.row.orderStatus" />
        </template>
      </el-table-column>
      <el-table-column :label="$t('sale.totalAmount')" align="center" prop="totalAmount" width="120" />
      <el-table-column :label="$t('common.createTime')" align="center" prop="createTime" width="160">
        <template #default="scope">
          <span>{{ parseTime(scope.row.createTime) }}</span>
        </template>
      </el-table-column>
      <el-table-column :label="$t('common.action')" width="200" align="center" class-name="small-padding fixed-width">
        <template #default="scope">
          <el-button link type="primary" icon="View" @click="handleDetail(scope.row)" v-hasPermi="['sale:order:query']">{{ $t('common.detail') }}</el-button>
          <el-button link type="primary" icon="Edit" @click="handleUpdate(scope.row)" v-hasPermi="['sale:order:edit']">{{ $t('common.edit') }}</el-button>
          <el-button link type="primary" icon="Delete" @click="handleDelete(scope.row)" v-hasPermi="['sale:order:remove']">{{ $t('common.delete') }}</el-button>
        </template>
      </el-table-column>
    </el-table>

    <pagination v-show="total > 0" :total="total" v-model:page="queryParams.pageNum" v-model:limit="queryParams.pageSize" @pagination="getList" />

    <!-- 新增/修改对话框 -->
    <el-dialog :title="dialogTitle" v-model="open" width="1000px" append-to-body>
      <el-form ref="orderRef" :model="form" :rules="rules" label-width="100px">
        <el-row>
          <el-col :span="8">
            <el-form-item :label="$t('sale.orderNo')" prop="orderNo">
              <el-input v-model="form.orderNo" :placeholder="$t('sale.autoGenerated')" disabled />
            </el-form-item>
          </el-col>
          <el-col :span="8">
            <el-form-item :label="$t('sale.customerName')" prop="customerName">
              <el-input v-model="form.customerName" :placeholder="$t('sale.customerNamePlaceholder')" />
            </el-form-item>
          </el-col>
          <el-col :span="8">
            <el-form-item :label="$t('sale.orderDate')" prop="orderDate">
              <el-date-picker v-model="form.orderDate" value-format="YYYY-MM-DD" type="date" :placeholder="$t('sale.selectDate')" style="width: 100%" />
            </el-form-item>
          </el-col>
        </el-row>
        <el-row>
          <el-col :span="8">
            <el-form-item :label="$t('sale.customerPhone')" prop="customerPhone">
              <el-input v-model="form.customerPhone" :placeholder="$t('sale.customerPhonePlaceholder')" />
            </el-form-item>
          </el-col>
          <el-col :span="16">
            <el-form-item :label="$t('sale.deliveryAddress')" prop="deliveryAddress">
              <el-input v-model="form.deliveryAddress" :placeholder="$t('sale.deliveryAddressPlaceholder')" />
            </el-form-item>
          </el-col>
        </el-row>
        <el-row>
          <el-col :span="24">
            <el-form-item :label="$t('common.remark')" prop="remark">
              <el-input v-model="form.remark" :placeholder="$t('common.remarkPlaceholder')" />
            </el-form-item>
          </el-col>
        </el-row>

        <!-- 明细子表格 -->
        <el-divider content-position="left">{{ $t('sale.orderItems') }}</el-divider>
        <el-row :gutter="10" class="mb8">
          <el-col :span="1.5">
            <el-button type="primary" plain icon="Plus" @click="handleAddItem">{{ $t('sale.addRow') }}</el-button>
          </el-col>
          <el-col :span="1.5">
            <el-button type="danger" plain icon="Delete" :disabled="itemSelection.length === 0" @click="handleDeleteItem">{{ $t('sale.deleteRow') }}</el-button>
          </el-col>
        </el-row>
        <el-table :data="form.orderDetailList" @selection-change="handleItemSelectionChange" border>
          <el-table-column type="selection" width="50" align="center" />
          <el-table-column :label="$t('sale.productName')" align="center" width="180">
            <template #default="scope">
              <el-input v-model="scope.row.productName" :placeholder="$t('sale.productNamePlaceholder')" />
            </template>
          </el-table-column>
          <el-table-column :label="$t('sale.productSpec')" align="center" width="160">
            <template #default="scope">
              <el-input v-model="scope.row.productSpec" :placeholder="$t('sale.productSpecPlaceholder')" />
            </template>
          </el-table-column>
          <el-table-column :label="$t('sale.unit')" align="center" width="80">
            <template #default="scope">
              <el-input v-model="scope.row.unit" :placeholder="$t('sale.unitPlaceholder')" />
            </template>
          </el-table-column>
          <el-table-column :label="$t('sale.quantity')" align="center" width="130">
            <template #default="scope">
              <el-input-number v-model="scope.row.quantity" :min="1" :precision="0" controls-position="right" @change="calcItemAmount(scope.row)" style="width: 100%" />
            </template>
          </el-table-column>
          <el-table-column :label="$t('sale.unitPrice')" align="center" width="130">
            <template #default="scope">
              <el-input-number v-model="scope.row.unitPrice" :min="0" :precision="2" controls-position="right" @change="calcItemAmount(scope.row)" style="width: 100%" />
            </template>
          </el-table-column>
          <el-table-column :label="$t('sale.amount')" align="center" width="120">
            <template #default="scope">
              <span>{{ scope.row.amount?.toFixed(2) }}</span>
            </template>
          </el-table-column>
        </el-table>
        <div style="text-align: right; margin-top: 10px; font-size: 16px; font-weight: bold;">
          {{ $t('sale.totalAmountLabel') }}{{ totalAmount.toFixed(2) }}
        </div>
      </el-form>
      <template #footer>
        <div class="dialog-footer">
          <el-button type="primary" @click="submitForm">{{ $t('common.confirm') }}</el-button>
          <el-button @click="cancel">{{ $t('common.cancel') }}</el-button>
        </div>
      </template>
    </el-dialog>

    <!-- 详情对话框 -->
    <el-dialog :title="$t('sale.detailTitle')" v-model="detailOpen" width="900px" append-to-body>
      <el-descriptions :column="3" border>
        <el-descriptions-item :label="$t('sale.orderNo')">{{ detailData.orderNo }}</el-descriptions-item>
        <el-descriptions-item :label="$t('sale.customerName')">{{ detailData.customerName }}</el-descriptions-item>
        <el-descriptions-item :label="$t('sale.customerPhone')">{{ detailData.customerPhone }}</el-descriptions-item>
        <el-descriptions-item :label="$t('sale.orderDate')">{{ detailData.orderDate }}</el-descriptions-item>
        <el-descriptions-item :label="$t('sale.orderStatus')">
          <dict-tag :options="sale_order_status" :value="detailData.orderStatus" />
        </el-descriptions-item>
        <el-descriptions-item :label="$t('sale.totalAmount')">{{ detailData.totalAmount?.toFixed(2) }}</el-descriptions-item>
        <el-descriptions-item :label="$t('sale.deliveryAddress')" :span="2">{{ detailData.deliveryAddress }}</el-descriptions-item>
        <el-descriptions-item :label="$t('common.remark')" :span="3">{{ detailData.remark }}</el-descriptions-item>
      </el-descriptions>
      <el-divider content-position="left">{{ $t('sale.orderItems') }}</el-divider>
      <el-table :data="detailData.orderDetailList" border>
        <el-table-column :label="$t('common.index')" type="index" width="60" align="center" />
        <el-table-column :label="$t('sale.productName')" align="center" prop="productName" />
        <el-table-column :label="$t('sale.productSpec')" align="center" prop="productSpec" />
        <el-table-column :label="$t('sale.unit')" align="center" prop="unit" width="80" />
        <el-table-column :label="$t('sale.quantity')" align="center" prop="quantity" width="100" />
        <el-table-column :label="$t('sale.unitPrice')" align="center" prop="unitPrice" width="100">
          <template #default="scope">
            <span>{{ scope.row.unitPrice?.toFixed(2) }}</span>
          </template>
        </el-table-column>
        <el-table-column :label="$t('sale.amount')" align="center" prop="amount" width="120">
          <template #default="scope">
            <span>{{ scope.row.amount?.toFixed(2) }}</span>
          </template>
        </el-table-column>
      </el-table>
      <template #footer>
        <div class="dialog-footer">
          <el-button @click="detailOpen = false">{{ $t('common.close') }}</el-button>
        </div>
      </template>
    </el-dialog>
  </div>
</template>

<script setup lang="ts" name="SaleOrder">
import { listOrder, listWithDetail, getOrder, addOrder, updateOrder, delOrder } from "@/api/sale/order"
import type { SaleOrderForm, SaleOrderItem, SaleOrderQuery } from '@/types/api/sale/order'

const { proxy } = getCurrentInstance() as any
const { sale_order_status } = useDict("sale_order_status")

const orderList = ref<any[]>([])
const open = ref(false)
const loading = ref(true)
const showSearch = ref(true)
const ids = ref<number[]>([])
const single = ref(true)
const multiple = ref(true)
const total = ref(0)
const dialogTitle = ref("")
const dateRange = ref<[string, string]>(['', ''])

/** 详情弹窗 */
const detailOpen = ref(false)
const detailData = ref<SaleOrderForm>({} as SaleOrderForm)

/** 明细行选中 */
const itemSelection = ref<SaleOrderItem[]>([])

const data = reactive({
  form: { orderDetailList: [] } as SaleOrderForm,
  queryParams: {
    pageNum: 1,
    pageSize: 10,
  } as SaleOrderQuery,
  rules: {
    customerName: [{ required: true, message: proxy.$t('sale.customerNameRequired'), trigger: "blur" }],
    orderDate: [{ required: true, message: proxy.$t('sale.orderDateRequired'), trigger: "change" }],
  },
})

const { queryParams, form, rules } = toRefs(data)

/** 合计金额 */
const totalAmount = computed(() => {
  return (form.value.orderDetailList || []).reduce((sum: number, item: SaleOrderItem) => sum + (item.amount || 0), 0)
})

/** 计算明细行金额 */
function calcItemAmount(row: SaleOrderItem) {
  row.amount = (row.quantity || 0) * (row.unitPrice || 0)
}

/** 查询列表 */
function getList() {
  loading.value = true
  listOrder(proxy.addDateRange(queryParams.value, dateRange.value)).then(res => {
    orderList.value = res.rows
    total.value = res.total
  }).finally(() => {
    loading.value = false
  })
}

/** 取消 */
function cancel() {
  open.value = false
  reset()
}

/** 表单重置 */
function reset() {
  form.value = {
    orderId: undefined,
    orderNo: undefined,
    customerName: undefined,
    customerPhone: undefined,
    orderDate: undefined,
    orderStatus: '0',
    deliveryAddress: undefined,
    remark: undefined,
    orderDetailList: [],
  }
  proxy.resetForm("orderRef")
}

/** 搜索 */
function handleQuery() {
  queryParams.value.pageNum = 1
  getList()
}

/** 重置 */
function resetQuery() {
  dateRange.value = ['', '']
  proxy.resetForm("queryRef")
  handleQuery()
}

/** 多选 */
function handleSelectionChange(selection: any[]) {
  ids.value = selection.map(item => item.orderId)
  single.value = selection.length !== 1
  multiple.value = !selection.length
}

/** 查看详情 */
function handleDetail(row: any) {
  listWithDetail({
    pageNum: 1,
    pageSize: 1,
    orderNo: row.orderNo,
  }).then(res => {
    if (res.rows && res.rows.length > 0) {
      detailData.value = res.rows[0]
      detailOpen.value = true
    }
  })
}

/** 新增 */
function handleAdd() {
  reset()
  open.value = true
  dialogTitle.value = proxy.$t('sale.addTitle')
}

/** 修改 */
function handleUpdate(row?: any) {
  reset()
  const orderId = row?.orderId || ids.value[0]
  getOrder(orderId).then(res => {
    const data = res.data!
    form.value = {
      orderId: data.orderId,
      orderNo: data.orderNo,
      customerName: data.customerName,
      customerPhone: data.customerPhone,
      orderDate: data.orderDate,
      orderStatus: data.orderStatus,
      deliveryAddress: data.deliveryAddress,
      remark: data.remark,
      orderDetailList: data.orderDetailList || [],
    }
    open.value = true
    dialogTitle.value = proxy.$t('sale.editTitle')
  })
}

/** 提交 */
function submitForm() {
  proxy.$refs["orderRef"].validate((valid: boolean) => {
    if (valid) {
      if (form.value.orderId != undefined) {
        updateOrder(form.value).then(() => {
          proxy.$modal.msgSuccess(proxy.$t('common.editSuccess'))
          open.value = false
          getList()
        })
      } else {
        addOrder(form.value).then(() => {
          proxy.$modal.msgSuccess(proxy.$t('common.addSuccess'))
          open.value = false
          getList()
        })
      }
    }
  })
}

/** 删除 */
function handleDelete(row?: any) {
  const orderIds = row?.orderId || ids.value
  const orderNo = row?.orderNo || ids.value.join(",")
  proxy.$modal.confirm(proxy.$t('sale.deleteConfirm', { no: orderNo })).then(() => {
    return delOrder(orderIds)
  }).then(() => {
    getList()
    proxy.$modal.msgSuccess(proxy.$t('common.deleteSuccess'))
  }).catch(() => {})
}

/** 导出 */
function handleExport() {
  proxy.download("sale/order/export", {
    ...queryParams.value
  }, `sale_order_${new Date().getTime()}.xlsx`)
}

/** 添加明细行 */
function handleAddItem() {
  form.value.orderDetailList = form.value.orderDetailList || []
  form.value.orderDetailList.push({
    productName: undefined,
    productSpec: undefined,
    unit: undefined,
    quantity: 1,
    unitPrice: 0,
    amount: 0,
  })
}

/** 删除明细行 */
function handleDeleteItem() {
  const selected = new Set(itemSelection.value)
  form.value.orderDetailList = form.value.orderDetailList.filter(item => !selected.has(item))
}

/** 明细行多选 */
function handleItemSelectionChange(selection: SaleOrderItem[]) {
  itemSelection.value = selection
}

getList()
</script>
